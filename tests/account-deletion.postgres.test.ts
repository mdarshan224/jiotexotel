// Run only against an isolated local PostgreSQL database after prisma db push.
// NODE_OPTIONS=--conditions=react-server npx tsx tests/account-deletion.postgres.test.ts
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile, access } from 'node:fs/promises';
import { db } from '../lib/db';
import { changeAccountDeletion, purgeCustomer, assertPhoneCanLogin } from '../lib/accountDeletion';
import { RECOVERY_MS, REJOIN_BLOCK_MS, phoneDigest } from '../lib/accountDeletionPolicy';
import { findOrCreateUserCustomer } from '../lib/services/customerService';

async function main() {
  const url = new URL(process.env.DATABASE_URL || '');
  assert(['localhost', '127.0.0.1'].includes(url.hostname) && url.pathname.includes('test'), 'Use an isolated local test DB');
  assert(process.env.NODE_ENV !== 'production' && !process.env.BLOB_READ_WRITE_TOKEN, 'No external storage in this test');
  process.env.ACCOUNT_DELETION_HMAC_SECRET = 'isolated-test-only-hmac-secret-over-32-characters';
  const suffix = randomUUID();
  const phone = '7' + String(Date.now()).slice(-9);
  const user = await findOrCreateUserCustomer(phone, 'Deletion test');
  const other = await db.user.create({ data: { phone: `other-${suffix}`, name: 'Unrelated customer', customer: { create: {} } } });
  const [first, duplicate] = await Promise.all([changeAccountDeletion(user.id, 'request'), changeAccountDeletion(user.id, 'request')]);
  assert.equal(first.deletionDueAt?.getTime(), duplicate.deletionDueAt?.getTime(), 'Concurrent requests must not extend deadline');
  assert.equal(first.deletionDueAt!.getTime() - first.deletionRequestedAt!.getTime(), RECOVERY_MS);
  assert.equal(first.tokenVersion, user.tokenVersion + 1);
  assert.equal(await purgeCustomer(user.id), false, 'Cannot delete before recovery deadline');
  const recovered = await changeAccountDeletion(user.id, 'recover');
  assert.equal(recovered.deletionDueAt, null);
  assert.equal(recovered.tokenVersion, first.tokenVersion + 1);
  await changeAccountDeletion(user.id, 'request');
  const customerId = user.customer!.id;
  const address = await db.address.create({ data: { userId: user.id, name: 'Private name', phone, houseNo:'1', street:'Private street', area:'Test',pincode:'560001', lat:12, lng:77 } });
  const agentUser = await db.user.create({data:{phone:`agent-${suffix}`,name:'Agent',role:'AGENT',agent:{create:{}}},include:{agent:true}});
  const agentWallet = await db.agentWallet.create({data:{agentId:agentUser.agent!.id,balance:50}});
  const photo = `/uploads/waste-photo-u_${user.id}-fixture.jpg`;
  const orphan = `/uploads/waste-photo-u_${user.id}-orphan.jpg`;
  await mkdir('storage/uploads', {recursive:true});
  await writeFile(`storage${photo}`, 'local photo fixture');
  await writeFile(`storage${orphan}`, 'unattached photo fixture');
  const order = await db.order.create({data:{orderNumber:suffix,customerId,addressId:address.id,agentId:agentUser.agent!.id,wastePhotos:JSON.stringify([photo])}});
  const agentEntry = await db.agentWalletTransaction.create({data:{walletId:agentWallet.id,agentId:agentUser.agent!.id,orderId:order.id,referenceId:order.id,reason:phone,type:'CREDIT',amount:50,balanceAfter:50}});
  const payment = await db.payment.create({data:{orderId:order.id,amount:100}});
  await db.refundRequest.create({data:{orderId:order.id,paymentId:payment.id,requestedByUserId:user.id,amount:100}});
  await db.refundAttempt.create({data:{id:suffix,orderId:order.id,paymentId:payment.id,amount:100,events:{create:{id:suffix,eventType:'TEST',details:{phone}}}}});
  await db.agentLocation.create({data:{agentId:agentUser.agent!.id,orderId:order.id,lat:12,lng:77}});
  await db.complaint.create({data:{customerId,orderId:order.id,description:'Private complaint',photoUrl:photo}});
  await db.review.create({data:{customerId,orderId:order.id,agentId:agentUser.agent!.id,comment:'Private review'}});
  await db.settlement.create({data:{customerId,orderId:order.id,totalWeightKg:1,amount:100,breakdownJson:'{}'}});
  await db.invoice.create({data:{orderId:order.id,invoiceNumber:suffix,totalAmount:100,pdfDataJson:JSON.stringify({phone})}});
  await db.weightRecord.create({data:{orderId:order.id,recordedByUserId:agentUser.id,weightJson:'{}',scalePhotoUrl:photo}});
  await db.notification.create({data:{userId:agentUser.id,orderId:order.id,recipient:agentUser.phone,content:phone}});
  await db.auditLog.create({data:{userId:agentUser.id,newValue:JSON.stringify({phone}),action:'TEST'}});
  await db.contactEnquiry.create({data:{name:'Private name',phone,email:'test@example.invalid',subject:'Test',message:'Private'}});
  const wallet = await db.customerWallet.create({data:{customerId}});
  const recharge = await db.walletTransaction.create({data:{walletId:wallet.id,customerId,type:'RECHARGE',amount:100}});
  const bonus = await db.walletTransaction.create({data:{walletId:wallet.id,customerId,type:'BONUS',amount:10}});
  const grant = await db.walletBonusGrant.create({data:{walletId:wallet.id,customerId,sourceTransactionId:bonus.id,rechargeTransactionId:recharge.id,grantedPaise:1000,remainingPaise:0}});
  await db.walletBonusConsumption.create({data:{grantId:grant.id,walletTransactionId:recharge.id,consumedPaise:1000}});
  const offer = await db.subscriptionOffer.create({data:{name:suffix,description:'Test',price:100}});
  const subPayment = await db.subscriptionPayment.create({data:{customerId,offerId:offer.id,amount:100}});
  const sub = await db.customerSubscription.create({data:{customerId,offerId:offer.id,paymentId:subPayment.id,startDate:new Date(),expiryDate:new Date(Date.now()+100000)}});
  await db.order.update({where:{id:order.id},data:{subscriptionId:sub.id}});
  await db.user.update({where:{id:user.id},data:{deletionDueAt:new Date(Date.now()-1)}});
  await assert.rejects(changeAccountDeletion(user.id,'recover'), /recovery window/);
  await assert.rejects(assertPhoneCanLogin(phone), /recovery window/);
  Object.assign(process.env, { NODE_ENV: 'production' });
  await assert.rejects(purgeCustomer(user.id), /Blob credentials/);
  assert.ok(await db.user.findUnique({where:{id:user.id}}), 'Storage failure must preserve retry metadata');
  Object.assign(process.env, { NODE_ENV: 'test' });
  const before = Date.now();
  assert.equal(await purgeCustomer(user.id), true);
  assert.equal(await purgeCustomer(user.id), false, 'Retry after success is idempotent');
  for (const model of ['user','customer','order','address','payment','refundRequest','refundAttempt','refundAttemptEvent','walletBonusGrant','walletBonusConsumption','customerWallet','walletTransaction','subscriptionPayment','customerSubscription','invoice','complaint','review','settlement','notification','weightRecord','auditLog','contactEnquiry'] as const) {
    if (model === 'user') assert.equal(await db.user.findUnique({where:{id:user.id}}),null);
    else if (model === 'customer') assert.equal(await db.customer.findUnique({where:{id:customerId}}),null);
    else assert.equal(await (db[model] as any).count(), 0, `${model} must be erased`);
  }
  await assert.rejects(access(`storage${photo}`));
  await assert.rejects(access(`storage${orphan}`));
  assert.ok(await db.user.findUnique({where:{id:other.id}}), 'Unrelated customer must survive');
  assert.ok(await db.user.findUnique({where:{id:agentUser.id}}), 'Agent must survive');
  const anonymousAgentEntry = await db.agentWalletTransaction.findUniqueOrThrow({where:{id:agentEntry.id}});
  assert.equal(anonymousAgentEntry.orderId,null);
  assert.equal(anonymousAgentEntry.referenceId,null);
  assert.equal(anonymousAgentEntry.amount,50);
  assert.equal(anonymousAgentEntry.reason,'Customer account deleted');
  const block = await db.deletedPhoneBlock.findUniqueOrThrow({where:{phoneHash:phoneDigest(phone)}});
  assert.ok(block.expiresAt.getTime() >= before + REJOIN_BLOCK_MS);
  await assert.rejects(findOrCreateUserCustomer(`+91${phone}`), /sign up again/);
  await db.deletedPhoneBlock.update({where:{phoneHash:block.phoneHash},data:{expiresAt:new Date(Date.now()-1)}});
  const rejoined = await findOrCreateUserCustomer(phone);
  assert.notEqual(rejoined.id,user.id,'Expired block permits a new empty account');
  console.log('PASS: concurrent request, 48-hour recovery, session revocation, full relational/file purge, idempotency, 30-day block and rejoining');
}
main().finally(() => db.$disconnect());
